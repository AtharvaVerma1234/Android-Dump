open class Cars(val name:String, val brand:String)
{
    open var range:Double=0.0

    fun extendRange(amount:Int)
    {
        if(amount>0)
            range+=amount
        println("Range modified in Cars Class")
    }
    open fun drive(distance:Double)
    {
        println("$brand $name has travelled $distance KM")
    }

}

